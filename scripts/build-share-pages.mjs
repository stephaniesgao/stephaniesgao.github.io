import {spawnSync} from 'node:child_process';
import {existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {allProjects, lockedPosts} from '../portfolio-content.mjs';

const root=fileURLToPath(new URL('../',import.meta.url));
const origin='https://stephaniesgao.github.io';
const author='Stephanie Gao';
const marker='<!-- Generated by scripts/build-share-pages.mjs -->';
const imageDirectory='og/blog';
const width=1200,height=630;
const sections=[
  {route:'projects',title:'Projects',description:'Apps, experiments, and design projects by Stephanie Gao.'},
  {route:'experiences',title:'Experiences',description:'Stephanie Gao’s work experience, education, and résumé.'},
  {route:'blog',title:'Blog',description:'Essays and notes by Stephanie Gao.'},
  {route:'places',title:'Places',description:'Postcards to the places that made Stephanie Gao.'},
  {route:'hobbies',title:'Outside of work',description:'Stephanie Gao’s interests outside of work.'}
];
const slugPattern=/^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const posts=JSON.parse(readFileSync(join(root,'blog-posts.json'),'utf8')).filter(post=>!lockedPosts.has(post.id));
const articlePages=posts.map(post=>({
  route:detailRoute('blog',post.id),title:post.title,description:post.subtitle||post.excerpt||`An essay by ${author}.`,
  image:`/${imageDirectory}/${post.id}.png`,id:post.id,type:'article'
}));
const projectPages=allProjects.map(project=>({
  route:detailRoute('projects',project.id),title:project.name,description:project.description
}));
const pages=[...sections,...articlePages,...projectPages];
const filenames=new Set(pages.map(page=>`${page.route}/index.html`));
if(filenames.size!==pages.length)throw new Error('Duplicate share routes');

function detailRoute(section,slug){
  if(typeof slug!=='string'||!slugPattern.test(slug))throw new Error(`Invalid ${section} slug: ${slug}`);
  return `${section}/${slug}`;
}

function escapeHtml(value){
  return value.replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
}

function sharePage({route,title,description,image='/og-image.png',type='website'}){
  const url=`${origin}/${route}/`,imageUrl=origin+image,target=`/#${route}`;
  const imageAlt=type==='article'?`${title} — ${author}`:"Screenshot of Stephanie Gao's portfolio homepage";
  const openGraph={type,site_name:author,title,description,url,image:imageUrl,'image:width':String(width),'image:height':String(height),'image:alt':imageAlt};
  const twitter={card:'summary_large_image',title,description,image:imageUrl};
  const meta=(prefix,attribute,values)=>Object.entries(values).map(([key,value])=>`  <meta ${attribute}="${prefix}:${key}" content="${escapeHtml(value)}">`).join('\n');
  return `<!doctype html>
${marker}
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <title>${escapeHtml(title)} | ${author}</title>
  <meta name="description" content="${escapeHtml(description)}">
  <link rel="canonical" href="${url}">
${meta('og','property',openGraph)}
${meta('twitter','name',twitter)}
  <meta http-equiv="refresh" content="0;url=${target}">
  <script>location.replace(${JSON.stringify(target)})</script>
</head>
<body>
  <p>Continue to <a href="${target}">${escapeHtml(title)}</a>.</p>
</body>
</html>
`;
}

function card({title,description}){
  return `<!doctype html><html lang="en"><meta charset="utf-8"><style>
*{box-sizing:border-box}
body{margin:0;background:#fff;color:#242424;font:24px/1.5 'Avenir Next',Avenir,'Segoe UI',sans-serif}
main{width:${width}px;height:${height}px;padding:56px 84px;display:grid;grid-template-rows:auto 1fr auto}
header,footer{color:#696969;letter-spacing:.04em}
header{padding-bottom:14px;border-bottom:1px solid #d7d7d7}
footer{padding-top:14px;border-top:1px solid #d7d7d7}
article{align-self:center}
h1{font-size:68px;line-height:1.08;font-weight:600;letter-spacing:-.045em;margin:0;text-wrap:balance}
p{font-size:30px;color:#696969;line-height:1.3;margin:24px 0 0;max-width:920px;text-wrap:pretty}
</style><main><header>Blog</header><article><h1>${escapeHtml(title)}</h1><p>${escapeHtml(description)}</p></article><footer>${author}</footer></main></html>`;
}

function renderImages(){
  if(!articlePages.length)return;
  const temp=mkdtempSync(join(tmpdir(),'portfolio-share-'));
  try{
    const input=join(temp,'card.html');
    for(const page of articlePages){
      writeFileSync(input,card(page));
      const screenshot=join(temp,`${page.id}.png`);
      const result=spawnSync(process.env.CHROME_BIN||'google-chrome',[
        '--headless','--hide-scrollbars','--disable-background-networking','--force-device-scale-factor=1',
        `--user-data-dir=${join(temp,'profile')}`,`--window-size=${width},${height}`,
        `--screenshot=${screenshot}`,pathToFileURL(input).href
      ],{encoding:'utf8',timeout:30_000});
      if(result.error||result.status!==0||!existsSync(screenshot)){
        throw new Error(`Chrome could not render ${page.route}: ${result.error||result.stderr}`);
      }
      const png=readFileSync(screenshot);
      if(png.readUInt32BE(16)!==width||png.readUInt32BE(20)!==height||png.length>=150_000){
        throw new Error(`Unexpected preview image dimensions or size for ${page.route}`);
      }
    }
    mkdirSync(join(root,imageDirectory),{recursive:true});
    for(const page of articlePages){
      writeFileSync(join(root,page.image.slice(1)),readFileSync(join(temp,`${page.id}.png`)));
    }
  }finally{
    rmSync(temp,{recursive:true,force:true,maxRetries:5});
  }
}

function removeStaleOutputs(){
  for(const section of ['blog','projects']){
    for(const entry of readdirSync(join(root,section),{withFileTypes:true})){
      if(!entry.isDirectory()||!slugPattern.test(entry.name))continue;
      const relative=`${section}/${entry.name}/index.html`,file=join(root,relative);
      if(!filenames.has(relative)&&existsSync(file)&&readFileSync(file,'utf8').includes(marker))rmSync(file);
    }
  }
  const directory=join(root,imageDirectory);
  if(!existsSync(directory))return;
  const imageNames=new Set(articlePages.map(page=>`${page.id}.png`));
  for(const entry of readdirSync(directory,{withFileTypes:true})){
    if(entry.isFile()&&entry.name.endsWith('.png')&&slugPattern.test(entry.name.slice(0,-4))&&!imageNames.has(entry.name)){
      rmSync(join(directory,entry.name));
    }
  }
}

renderImages();
for(const page of pages){
  const directory=join(root,page.route);
  mkdirSync(directory,{recursive:true});
  writeFileSync(join(directory,'index.html'),sharePage(page));
}
removeStaleOutputs();
console.log(`Generated ${pages.length} share pages and ${articlePages.length} blog preview images.`);
